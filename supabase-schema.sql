-- FieldStation v0.2 — Supabase schema
-- Run this entire file in Supabase Dashboard → SQL Editor.
-- Uses per-user row-level security. Never put a service_role key in the app.

create table if not exists public.station_daily_records (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  location_key text not null,
  location_name text not null,
  latitude double precision not null,
  longitude double precision not null,
  record_date date not null,
  record_type text not null check (record_type in ('reanalysis_estimate','forecast_snapshot','station_observation')),
  source text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint station_daily_records_user_location_date_type_key
    unique (user_id, location_key, record_date, record_type)
);

create index if not exists station_daily_records_user_date_idx
  on public.station_daily_records (user_id, record_date desc);
create index if not exists station_daily_records_user_location_idx
  on public.station_daily_records (user_id, location_key, record_date desc);

alter table public.station_daily_records enable row level security;

 drop policy if exists "Users can read their own station records" on public.station_daily_records;
create policy "Users can read their own station records"
  on public.station_daily_records for select
  using (auth.uid() = user_id);

 drop policy if exists "Users can insert their own station records" on public.station_daily_records;
create policy "Users can insert their own station records"
  on public.station_daily_records for insert
  with check (auth.uid() = user_id);

 drop policy if exists "Users can update their own station records" on public.station_daily_records;
create policy "Users can update their own station records"
  on public.station_daily_records for update
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

 drop policy if exists "Users can delete their own station records" on public.station_daily_records;
create policy "Users can delete their own station records"
  on public.station_daily_records for delete
  using (auth.uid() = user_id);

-- No anonymous/public access policies are created.
